import { insertWorld } from "@repo/db/queries/insert";
import {
  selectDocument,
  selectProjectById,
  selectWorldById,
} from "@repo/db/queries/select";
import { updateProject, updateWorld } from "@repo/db/queries/update";
import type { WorldRow } from "@repo/db/type";
import { since } from "@repo/logger";
import {
  WorldLabsError,
  createWorldLabsClient,
  extractWorldAssets,
  type World,
} from "@repo/world";
import { Hono } from "hono";
import { HTTPException } from "hono/http-exception";
import { log } from "../logging";
import { projectPath, readFile, writeFile, writeJson } from "../storage";

/**
 * A project's own 3D world, generated by World Labs from one of its kept
 * panoramas and copied into the project's files once ready. Generation takes
 * about five minutes, so the page starts it, then asks for its status until
 * it is ready. A project without a world uses the bundled demo world.
 */
export const projectWorld = new Hono();

const UUID =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
// The files a viewer loads, as the bundled demo world names them.
const FILES = {
  "world.json": "application/json",
  "world.spz": "application/octet-stream",
  "collider.glb": "model/gltf-binary",
  "pano.png": "image/png",
} as const;
type WorldFile = keyof typeof FILES;

const fail = (status: 400 | 404 | 409 | 503, message: string): never => {
  throw new HTTPException(status, { message });
};

function worldLabs() {
  const apiKey = process.env.WORLD_LABS_API_KEY;
  if (!apiKey) fail(503, "WORLD_LABS_API_KEY is not set");
  if (!process.env.GCS_BUCKET) fail(503, "GCS_BUCKET is not set");
  return createWorldLabsClient({
    apiKey: apiKey!,
    baseUrl: process.env.WORLD_LABS_API_BASE || undefined,
  });
}

async function project(id: string) {
  if (!UUID.test(id)) fail(404, "No such project");
  const row = await selectProjectById(id);
  if (!row) fail(404, "No such project");
  return row!;
}

projectWorld.onError((error, c) => {
  if (error instanceof HTTPException) {
    return c.json({ error: error.message }, error.status);
  }
  if (error instanceof WorldLabsError) {
    // Missing credits and bad images are the user's to fix.
    const status = error.status === 402 ? 402 : error.status === 400 ? 400 : 502;
    return c.json({ error: `World Labs: ${error.message}` }, status);
  }
  log.error("world request failed", { error });
  return c.json({ error: "The 3D world could not be built or loaded" }, 500);
});

/** A world as the page shows it. */
const summary = (row: WorldRow, progress?: string | null) => ({
  id: row.id,
  status: row.status,
  error: row.lastError ?? undefined,
  progress: progress ?? undefined,
  startedAt: row.createdAt.getTime(),
});

// Worlds being copied into the bucket by this instance, so two status checks
// at once do not copy twice.
const copying = new Map<string, Promise<void>>();

async function download(url: string) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Downloading ${url} failed: HTTP ${response.status}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

/** Copies a finished world's files from World Labs into the project's files. */
async function copyWorld(projectId: string, row: WorldRow, world: World) {
  const assets = extractWorldAssets(world);
  if (!assets.colliderMeshUrl) throw new Error("The world has no collider mesh");
  if (!assets.panoUrl) throw new Error("The world has no panorama");
  const path = (name: WorldFile) => projectPath(projectId, "world", row.id, name);
  const started = performance.now();
  const [splat, collider, pano] = await Promise.all([
    // The 500k splat loads quickly and is what the demo world uses.
    download(assets.spzUrls["500k"] ?? assets.splatUrl),
    download(assets.colliderMeshUrl),
    download(assets.panoUrl),
  ]);
  await Promise.all([
    writeFile(path("world.spz"), splat, FILES["world.spz"]),
    writeFile(path("collider.glb"), collider, FILES["collider.glb"]),
    writeFile(path("pano.png"), pano, FILES["pano.png"]),
    writeJson(path("world.json"), world),
  ]);
  await updateWorld(row.id, {
    status: "ready",
    worldLabsId: assets.worldId,
    splatPath: path("world.spz"),
    colliderPath: path("collider.glb"),
    panoPath: path("pano.png"),
    record: world,
  });
  log.info("world copied", {
    project: projectId,
    world: row.id,
    megabytes: Math.round((splat.length + collider.length + pano.length) / 1e5) / 10,
    ms: since(started),
  });
}

/**
 * Starts building the project's world from one of its kept panoramas:
 * { documentId }. Answers at once; the world is ready in about five minutes.
 */
projectWorld.post("/:id/world", async (c) => {
  const id = c.req.param("id");
  const row = await project(id);
  const body = (await c.req.json().catch(() => null)) as {
    documentId?: unknown;
  } | null;
  const documentId = body?.documentId;
  if (typeof documentId !== "string" || !UUID.test(documentId)) {
    fail(400, "Expected { documentId } of a kept panorama");
  }
  const panorama = await selectDocument(id, documentId as string);
  if (!panorama || panorama.kind !== "panorama") {
    fail(404, "No such panorama in this project");
  }
  if (row.worldId) {
    const current = await selectWorldById(row.worldId);
    if (current?.status === "generating") {
      fail(409, "A 3D world is already being built for this project");
    }
  }
  const client = worldLabs();
  const file = await readFile(panorama!.path);
  if (!file) fail(404, "The panorama's file is no longer kept");

  const started = performance.now();
  // The bucket is private, so the panorama goes to World Labs as an upload.
  const mediaAssetId = await client.uploadImage(
    panorama!.name.replace(/[^\w.-]+/g, "_") || "panorama.jpg",
    new Uint8Array(file!.data),
    file!.contentType,
  );
  const operation = await client.generateWorld({
    world_prompt: {
      type: "image",
      image_prompt: { source: "media_asset", media_asset_id: mediaAssetId },
      is_pano: true,
    },
    display_name: row.name.slice(0, 64),
  });
  const worldId = await insertWorld({
    name: row.name,
    operationId: operation.operation_id,
    status: "generating",
  });
  await updateProject(id, { worldId });
  log.info("world started", {
    project: id,
    world: worldId,
    operation: operation.operation_id,
    ms: since(started),
  });
  const world = await selectWorldById(worldId);
  return c.json({ world: summary(world!) }, 202);
});

/**
 * The project's world: null when it uses the demo world. While generating,
 * this asks World Labs how far it got; once done, it copies the files into
 * the project's files and answers ready.
 */
projectWorld.get("/:id/world", async (c) => {
  const id = c.req.param("id");
  const row = await project(id);
  if (!row.worldId) return c.json({ world: null });
  let world = await selectWorldById(row.worldId);
  if (!world) return c.json({ world: null });
  if (world.status !== "generating" || !world.operationId) {
    return c.json({ world: summary(world) });
  }

  const operation = await worldLabs().getOperation(world.operationId);
  if (!operation.done) {
    return c.json({
      world: summary(world, operation.metadata?.progress?.description),
    });
  }
  if (operation.error || !operation.response) {
    await updateWorld(world.id, {
      status: "failed",
      lastError: operation.error?.message ?? "World Labs could not build the world",
    });
  } else {
    let copy = copying.get(world.id);
    if (!copy) {
      copy = copyWorld(id, world, operation.response)
        .catch(async (error: unknown) => {
          log.error("world copy failed", { project: id, world: world!.id, error });
          await updateWorld(world!.id, {
            status: "failed",
            lastError: "The world was built but could not be saved; build it again",
          });
        })
        .finally(() => copying.delete(world!.id));
      copying.set(world.id, copy);
    }
    await copy;
  }
  world = await selectWorldById(world.id);
  return c.json({ world: summary(world!) });
});

/** One of the ready world's files, named as the viewer loads them. */
projectWorld.get("/:id/world/files/:name", async (c) => {
  const id = c.req.param("id");
  const name = c.req.param("name") as WorldFile;
  if (!(name in FILES)) fail(404, "No such file");
  const row = await project(id);
  const world = row.worldId ? await selectWorldById(row.worldId) : null;
  if (world?.status !== "ready") fail(404, "This project has no 3D world yet");
  const file = await readFile(projectPath(id, "world", world!.id, name));
  if (!file) fail(404, "No such file");
  return new Response(new Uint8Array(file!.data), {
    headers: {
      "Content-Type": FILES[name],
      // A world's files never change; a new world gets a new folder.
      "Cache-Control": "private, max-age=86400",
    },
  });
});

/** Goes back to the demo world; the built world's files stay until deleted. */
projectWorld.delete("/:id/world", async (c) => {
  const id = c.req.param("id");
  await project(id);
  await updateProject(id, { worldId: null });
  return c.body(null, 204);
});
